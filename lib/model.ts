// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) and every other pre-token protocol the radar can rank below that
// floor: the early rows the radar exists to find. A protocol is pre-token when
// its record carries no token (no market cap, no CoinGecko id, no symbol);
// live-token protocols are kept apart and shown with the market's own values,
// never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, one function
// for every protocol, no name ever special-cased:
//
//   base        = tvl_usd x BASE_MULTIPLE
//   growth      = clamp(change_7d, -60, 120) per cent; a fall counts 1.5x,
//                 because a protocol bleeding TVL is a worse launch bet
//                 than a flat one, and the downside is capped so one bad
//                 week cannot zero a strong protocol
//   growthMult  = 1 + (growth / 100) x GROWTH_WEIGHT, floored at 0.55
//   maturity    = 0.5 + min(age_days, 1460) / 1460 x 0.4
//                 (age is the time since first listing: how long the
//                 protocol has run with no token; unknown age uses 365)
//   overdueMult = 1 + 0.08 x min(max(age_days - 730, 0) / 730, 1)
//                 (a launch delayed past two years is overdue: the longer
//                 the wait, the closer the launch is likely to be)
//   breadth     = 1 + 0.02 x min(chains, 5)
//                 (a protocol live on more chains reaches more users)
//   implied     = max(1, round(base x growthMult x maturity x overdueMult
//                 x breadth))
//
// The dashboard states these constants and its sandbox lets a reader change
// them and re-rank the board live, so the model is a function anyone can
// audit, not a list of names.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
